// M12.4: NetworkAdminService — network info + hostname/DNS/interface management
// @see docs/phases/phase-12.md

import { DomainService, ok, fail, type ServiceResult } from '../base.js';
import {
  shellEscape,
  validateHostname,
  validateIpAddress,
  validateInterfaceName,
} from '../../../security/validators.js';
import {
  parseSsListening,
  parseSsConnections,
} from '../../../parsers/deterministic/ss.js';
import {
  parseIpRoute,
  parseResolvConf,
  parseIpLinkShow,
} from '../../../parsers/deterministic/ip-route.js';
import {
  NetworkInfoSchema,
  type NetworkInfo,
} from '../../../parsers/schemas/serveradmin.js';

export class NetworkAdminService extends DomainService {
  async getNetworkInfo(serverId: string): Promise<ServiceResult<NetworkInfo>> {
    this.requireConnected(serverId);
    const [ports, conns, routes, dns, links, host] = await Promise.all([
      this.safeExec(serverId, 'ss -tlnp'),
      this.safeExec(serverId, 'ss -tunap'),
      this.safeExec(serverId, 'ip route show'),
      this.safeExec(serverId, 'cat /etc/resolv.conf'),
      this.safeExec(serverId, 'ip -o link show'),
      this.safeExec(serverId, 'hostname'),
    ]);
    const data = NetworkInfoSchema.parse({
      hostname: host.trim() || undefined,
      ports: parseSsListening(ports),
      connections: parseSsConnections(conns),
      routes: parseIpRoute(routes),
      dns: parseResolvConf(dns),
      interfaces: parseIpLinkShow(links),
    });
    return ok(data);
  }

  async setHostname(
    serverId: string,
    hostname: string,
  ): Promise<ServiceResult<{ message: string }>> {
    this.requireConnected(serverId);
    if (!validateHostname(hostname)) return fail('Invalid hostname (RFC 1123)', 400);
    return this.execAction(
      serverId,
      `sudo hostnamectl set-hostname ${shellEscape(hostname)}`,
      `Hostname set to ${hostname}`,
    );
  }

  async setDns(
    serverId: string,
    nameservers: string[],
    searchDomains?: string[],
  ): Promise<ServiceResult<{ message: string }>> {
    this.requireConnected(serverId);
    if (nameservers.length === 0) {
      return fail('At least one nameserver is required', 400);
    }
    for (const ns of nameservers) {
      if (!validateIpAddress(ns)) return fail(`Invalid nameserver IP: ${ns}`, 400);
    }
    if (searchDomains) {
      for (const d of searchDomains) {
        if (!validateHostname(d)) return fail(`Invalid search domain: ${d}`, 400);
      }
    }
    let content = '# Generated by HeadlessOS\n';
    for (const ns of nameservers) content += `nameserver ${ns}\n`;
    if (searchDomains?.length) content += `search ${searchDomains.join(' ')}\n`;

    return this.execAction(
      serverId,
      `echo ${shellEscape(content)} | sudo tee /etc/resolv.conf > /dev/null`,
      'DNS configuration updated',
    );
  }

  async interfaceUp(
    serverId: string,
    name: string,
  ): Promise<ServiceResult<{ message: string }>> {
    this.requireConnected(serverId);
    if (!validateInterfaceName(name)) return fail('Invalid interface name', 400);
    return this.execAction(
      serverId,
      `sudo ip link set ${shellEscape(name)} up`,
      `Interface ${name} is up`,
    );
  }

  async interfaceDown(
    serverId: string,
    name: string,
  ): Promise<ServiceResult<{ message: string }>> {
    this.requireConnected(serverId);
    if (!validateInterfaceName(name)) return fail('Invalid interface name', 400);
    return this.execAction(
      serverId,
      `sudo ip link set ${shellEscape(name)} down`,
      `Interface ${name} is down`,
    );
  }
}
